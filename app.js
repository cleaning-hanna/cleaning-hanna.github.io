const LANGUAGE_KEY = "hanna-cleaning-language";
const allowedLanguages = new Set(Object.keys(translations));
const languageSelect = document.querySelector("#language");
const menuToggle = document.querySelector("#menu-toggle");
const nav = document.querySelector("#site-nav");
const backToTop = document.querySelector("#back-to-top");

function detectLanguage() {
  try {
    const saved = window.localStorage.getItem(LANGUAGE_KEY);
    if (saved && allowedLanguages.has(saved)) return saved;
  } catch { /* Storage can be disabled by the browser. */ }
  const preferences = navigator.languages?.length ? navigator.languages : [navigator.language];
  for (const preference of preferences) {
    const base = String(preference || "").toLowerCase().split("-")[0];
    if (allowedLanguages.has(base)) return base;
  }
  return "pl";
}

function translate(language) {
  const lang = allowedLanguages.has(language) ? language : "pl";
  const strings = translations[lang];
  document.documentElement.lang = lang;
  languageSelect.value = lang;
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = strings[element.dataset.i18n];
    if (value !== undefined) element.textContent = value;
  });
  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const value = strings[element.dataset.i18nAlt];
    if (value !== undefined) element.setAttribute("alt", value);
  });
  document.title = strings.metaTitle;
  document.querySelector('meta[name="description"]').content = strings.metaDescription;
  document.querySelector('meta[property="og:title"]').content = strings.metaTitle;
  document.querySelector('meta[property="og:description"]').content = strings.metaOgDescription;
  document.querySelector('meta[property="og:locale"]').content = ({pl:"pl_PL",uk:"uk_UA",ru:"ru_RU",en:"en_US"})[lang];
  menuToggle.setAttribute("aria-label", strings[menuToggle.getAttribute("aria-expanded") === "true" ? "ariaMenuClose" : "ariaMenuOpen"]);
  backToTop.setAttribute("aria-label", strings.ariaTop);
  backToTop.title = strings.ariaTop;
  document.querySelector("#site-nav").setAttribute("aria-label", strings.navServices);
}

function closeMenu() {
  nav.classList.remove("open");
  document.body.classList.remove("menu-open");
  menuToggle.setAttribute("aria-expanded", "false");
  menuToggle.setAttribute("aria-label", translations[languageSelect.value].ariaMenuOpen);
}

languageSelect.addEventListener("change", (event) => {
  const lang = allowedLanguages.has(event.target.value) ? event.target.value : "pl";
  try { window.localStorage.setItem(LANGUAGE_KEY, lang); } catch {}
  // Explicit language URLs are crawlable and bookmarkable.
  window.location.assign("/" + lang + "/" + window.location.hash);
});
menuToggle.addEventListener("click", () => {
  const open = menuToggle.getAttribute("aria-expanded") !== "true";
  nav.classList.toggle("open", open);
  document.body.classList.toggle("menu-open", open);
  menuToggle.setAttribute("aria-expanded", String(open));
  menuToggle.setAttribute("aria-label", translations[languageSelect.value][open ? "ariaMenuClose" : "ariaMenuOpen"]);
});
nav.querySelectorAll("a").forEach((link) => link.addEventListener("click", closeMenu));
window.addEventListener("resize", () => { if (window.innerWidth > 820) closeMenu(); }, {passive:true});
